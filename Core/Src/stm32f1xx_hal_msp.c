/**
  * Initializes the Global MSP.
  */
void HAL_MspInit(void)
{

  /* USER CODE BEGIN MspInit 0 */

  /* USER CODE END MspInit 0 */

  __HAL_RCC_AFIO_CLK_ENABLE();
  __HAL_RCC_PWR_CLK_ENABLE();

  /* System interrupt init*/

  /** DISABLE: JTAG-DP Disabled and SW-DP Enabled
   *
   * 电控第一次作业 关键修正:
   *   原来这里是 __HAL_AFIO_REMAP_SWJ_DISABLE(), 会把 JTAG 和 SWD 一起关掉,
   *   导致程序下载一次之后板子的 SWD 被锁死, 再也无法烧录,
   *   只能靠 BOOT0 跳线从系统存储器启动, 或用 USB 擦除全部闪存来救。
   *
   *   因为 CubeMX 里 SYS -> Debug 选的是 Serial Wire,
   *   所以这里必须用 NOJTAG 版本: 关闭 JTAG(释放 PA15/PB3/PB4), 但保留 SWD。
   */
  __HAL_AFIO_REMAP_SWJ_NOJTAG();

  /* USER CODE BEGIN MspInit 1 */

  /* USER CODE END MspInit 1 */
}

